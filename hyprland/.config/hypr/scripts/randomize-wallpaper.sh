#!/usr/bin/env bash
# Pick a random wallpaper from DIR (never the one already on screen) and apply it
# to every monitor, then re-theme the desktop from it.
#
#   randomize-wallpaper.sh [DIR] [WAIT_MS]
#
# DIR      wallpapers to pick from                      (default: ~/Pictures/wallpapers/rotation)
# WAIT_MS  how long to wait for hyprpaper's IPC to answer              (default: 2000)
#
# If hyprpaper is already running it's a hot swap over IPC (~5-10ms per monitor).
# If it isn't -- i.e. session start -- it generates hyprpaper's config from the
# live monitor list and starts it, so the first wallpaper ever drawn is already
# the right one instead of whatever was left in a config file.
set -euo pipefail

WALLPAPER_DIR="${1:-$HOME/Pictures/wallpapers/rotation}"
WAIT_MS="${2:-2000}"
CACHE="$HOME/.cache/current-wallpaper"
CONF="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/hyprpaper.conf"

now_ms() { date +%s%3N; }

wait_for_ipc() {
  local deadline=$(( $(now_ms) + WAIT_MS ))
  until running; do
    if (( $(now_ms) >= deadline )); then
      echo "randomize-wallpaper: hyprpaper IPC not answering after ${WAIT_MS}ms" >&2
      return 1
    fi
    sleep 0.02
  done
}

running() { hyprctl hyprpaper listactive >/dev/null 2>&1; }

start_hyprpaper() {
  setsid -f hyprpaper >/dev/null 2>&1 </dev/null
  wait_for_ipc
}

# --- choose files ----------------------------------------------------------

mapfile -t FILES < <(find -L "$WALLPAPER_DIR" -type f -readable)
if ((${#FILES[@]} == 0)); then
  echo "randomize-wallpaper: no wallpapers in $WALLPAPER_DIR" >&2
  # Better a stale wallpaper than a bare desktop: if a config from a previous
  # run survived, hyprpaper can still come up with it.
  if ! running && [[ -f $CONF ]]; then start_hyprpaper || true; fi
  exit 1
fi

# Skip whatever is currently applied so every run actually changes the picture.
CURRENT=""
if [[ -s "$CACHE" ]]; then
  CURRENT="$(readlink -f -- "$(head -n1 "$CACHE")" 2>/dev/null || true)"
fi

CAND=()
if [[ -n "$CURRENT" ]]; then
  for f in "${FILES[@]}"; do
    [[ "$(readlink -f -- "$f")" == "$CURRENT" ]] || CAND+=("$f")
  done
fi
((${#CAND[@]})) || CAND=("${FILES[@]}")  # single wallpaper in the dir

SRC="$(printf '%s\n' "${CAND[@]}" | shuf -n1)"
REAL_SRC="$(readlink -f -- "$SRC")"

# --- monitors --------------------------------------------------------------

mapfile -t MONS < <(hyprctl -j monitors | jq -r '.[].name')
((${#MONS[@]})) || { echo "randomize-wallpaper: no monitors found" >&2; exit 1; }

# --- generate hyprpaper's config (cold start) ------------------------------

# The config is derived, never hand-edited: rewritten from the monitor list that
# actually exists right now. hyprpaper has no wildcard monitor, so a stale entry
# means that output silently gets no wallpaper at all.
write_conf() {
  local src=$1 m
  shift
  mkdir -p "$(dirname "$CONF")"
  [[ -L "$CONF" ]] && rm -f "$CONF"  # never write through a stow symlink
  {
    echo "# Generated by randomize-wallpaper.sh -- do not edit."
    echo
    for m in "$@"; do
      printf 'wallpaper {\n    monitor = %s\n    path = %s\n    fit_mode = cover\n}\n\n' "$m" "$src"
    done
    echo "splash = false"
  } > "$CONF"
}

# --- apply wallpapers ------------------------------------------------------

# Always rewritten, cold or warm, so the file on disk is never behind what is
# actually on screen (a manual `hyprpaper` restart then restores this one).
write_conf "$REAL_SRC" "${MONS[@]}"

if ! running; then
  # A hyprpaper that answers no IPC is a leftover from a dead session; two of
  # them would fight over the outputs.
  pkill -x hyprpaper 2>/dev/null || true
  start_hyprpaper
fi

# Same call in both paths: on cold start the image is already preloaded by the
# config, so this is a cache hit that just guarantees what we asked for is live.
for m in "${MONS[@]}"; do
  hyprctl hyprpaper wallpaper "$m,$REAL_SRC,cover"
done

# Recorded before re-theming: if matugen fails, the wallpaper is still current.
printf '%s\n' "$REAL_SRC" > "$CACHE"

# --- theme ----------------------------------------------------------------

set-theme "$REAL_SRC"
